import React from 'react';
import { act, fireEvent, render, screen } from '@testing-library/react';
import { describe, expect, it, vi, beforeEach } from 'vitest';
import type { Community } from '@zktalk/shared';
import { ChannelSidebar } from '../ChannelSidebar';
import { getCollapsedSectionState } from '@/lib/user-settings';












































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































vi.mock('next/link', () => ({
  default: ({ href, children, ...rest }: React.AnchorHTMLAttributes<HTMLAnchorElement> & { href: string }) => (
    <a href={href} {...rest}>{children}</a>
  ),
}));

vi.mock('next/navigation', () => ({
  useParams: () => ({ channelId: 'channel-1' }),
}));

vi.mock('@/lib/i18n', () => ({
  useTranslation: () => ({
    t: (key: string, values?: Record<string, string | number>) => values?.count ?? values?.name ?? key,
  }),
}));

vi.mock('@/lib/api', () => ({
  api: vi.fn(async (path: string) => {
    if (path.includes('/members')) {
      return { members: [{ id: 'member-1', userId: 'user-1' }] };
    }
    if (path.includes('/channels')) {
      return {
        uncategorized: [],
        categories: [
          {
            category: { id: 'cat-1', name: 'General', position: 0 },
            channels: [
              {
                id: 'channel-1',
                name: 'general',
                type: 'chat',
                position: 0,
                isArchived: false,
                categoryId: 'cat-1',
              },
            ],
          },
        ],
      };
    }
    if (path.includes('/voice/participants')) {
      return { participants: [] };
    }
    return {};
  }),
}));

vi.mock('@/hooks/usePresence', () => ({
  usePresence: () => ({ onlineCount: 0 }),
}));

vi.mock('@/stores/unread', () => ({
  useUnreadStore: () => ({
    unreadMap: {},
    fetchUnread: vi.fn(),
  }),
}));

vi.mock('@/components/VoiceRoom', () => ({
  VoiceRoomButton: () => <button type="button">VoiceRoomButtonMock</button>,
}));

const community: Community = {
  id: 'community-1',
  slug: 'alpha-team',
  name: 'Alpha Team',
  description: null,
  iconUrl: null,
  bannerUrl: null,
  visibility: 'public',
  ownerUserId: 'user-1',
  createdAt: '2026-03-27T00:00:00.000Z',
  updatedAt: '2026-03-27T00:00:00.000Z',
};

describe('ChannelSidebar', () => {
  beforeEach(() => {
    window.localStorage.clear();
  });

  it('persists category collapse state in shared settings cache', async () => {
    render(<ChannelSidebar community={community} />);

    const categoryToggle = await screen.findByRole('button', { name: /General/i });
    expect(getCollapsedSectionState('channel-sidebar:alpha-team:cat-1')).toBe(false);

    act(() => {
      fireEvent.click(categoryToggle);
    });

    expect(getCollapsedSectionState('channel-sidebar:alpha-team:cat-1')).toBe(true);
  });
});
